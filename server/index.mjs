import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {Store} from './store.mjs';
import {WorkerPool} from './workers.mjs';
import {createApp} from './app.mjs';
import {createAttachmentDelivery} from './attachments.mjs';
import {readStateKey, stateLayout} from './state.mjs';
const origin=new URL(process.env.PUBLIC_URL).origin;
const layout=stateLayout();
const store=new Store(layout.database,readStateKey(layout));
const pool=new WorkerPool({store,layout});
const attachments=await createAttachmentDelivery({store,layout,origin});
const {sendAuthorizationPage:render}=await import(pathToFileURL(process.env.AUTH_UI_RENDERER||'/opt/mcp/auth-ui/server/render.mjs').href);
const app=createApp({store,pool,origin,render,attachments,staticDir:resolve('out'),registrationEnabled:process.env.ALLOW_REGISTRATION==='true'});
const server=app.listen(Number(process.env.PORT||3186),'127.0.0.1',()=>console.log('MCP center ready'));
for(const sig of ['SIGTERM','SIGINT'])process.on(sig,()=>{server.close(()=>{attachments.close();pool.close();store.close();process.exit(0);});setTimeout(()=>process.exit(1),10000).unref();});
